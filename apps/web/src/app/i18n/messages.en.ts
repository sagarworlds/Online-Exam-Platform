/** The key of a message. */
export type MessageKey = keyof typeof EN;

/** A complete set of messages for one language: the compiler rejects a file that misses or invents a key. */
export type Messages = Record<MessageKey, string>;

/** The keys that come in `.one` and `.other` forms, named without the suffix. */
export type PluralKey = MessageKey extends infer K ? (K extends `${infer Base}.one` ? Base : never) : never;
